"""
OnyxSi v1.0 — Pure Headless Zero-Dependency Autonomous Agent Kernel.

Root facade exposing the public surface of every subsystem layer:

  Layer 0  contracts      — OnyxError / OnyxErrorCode / data contracts
  Layer 1  hal            — shared memory plane, ring buffer, supervisor
  Layer 2  contextfs      — bitplane AST scanner, piece table, token governor
  Layer 3  deltafs        — ghost-CoW overlay, delta map, AST lease & merger
  Layer 4  gateway        — 8-meta-tool router, policy gate, grammar shield
  Layer 5  causal         — trajectory, error budget, bisect, antibody memory
  Layer 6  knowledge      — task wiki, CSR+BM25, blast runner, compute ALU

Importing this package pulls the whole kernel in; for a lean import use the
sub-package paths directly (e.g. ``from onyxsi.contextfs.piece_table import ...``).
100% Python Standard Library only.
"""

